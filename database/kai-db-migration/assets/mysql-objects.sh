#!/bin/bash
# 객체 인벤토리 — GATE 3 / GATE 7-1.  사용: mysql-objects.sh <DB>
# ⚠️ 개수만이 아니라 **이름 문자열까지** 뽑는다. 개수가 같아도 대소문자가 다를 수 있다.
# ⚠️ 컬럼 구분에 CONCAT('\t') 를 쓰지 않는다 — mysql -B 는 값 안의 탭을 \t 로 이스케이프해
#    한 칸에 뭉개진다. 컬럼을 나눠 select 하면 배치 모드가 진짜 탭으로 구분해 준다. (실제로 겪음)
set -uo pipefail
DB="${1:?DB 이름 필요}"
. "$(dirname "$0")/_conn.sh"

myq "
SELECT 'COUNT', k, c FROM (
  SELECT 'table' k, COUNT(*) c FROM information_schema.TABLES
    WHERE TABLE_SCHEMA='$DB' AND TABLE_TYPE='BASE TABLE'
  UNION ALL SELECT 'view', COUNT(*) FROM information_schema.TABLES
    WHERE TABLE_SCHEMA='$DB' AND TABLE_TYPE='VIEW'
  UNION ALL SELECT 'procedure', COUNT(*) FROM information_schema.ROUTINES
    WHERE ROUTINE_SCHEMA='$DB' AND ROUTINE_TYPE='PROCEDURE'
  UNION ALL SELECT 'function', COUNT(*) FROM information_schema.ROUTINES
    WHERE ROUTINE_SCHEMA='$DB' AND ROUTINE_TYPE='FUNCTION'
  UNION ALL SELECT 'trigger', COUNT(*) FROM information_schema.TRIGGERS
    WHERE TRIGGER_SCHEMA='$DB'
  UNION ALL SELECT 'event', COUNT(*) FROM information_schema.EVENTS
    WHERE EVENT_SCHEMA='$DB'
  UNION ALL SELECT 'foreign_key', COUNT(*) FROM information_schema.TABLE_CONSTRAINTS
    WHERE TABLE_SCHEMA='$DB' AND CONSTRAINT_TYPE='FOREIGN KEY'
  UNION ALL SELECT 'unique_key', COUNT(*) FROM information_schema.TABLE_CONSTRAINTS
    WHERE TABLE_SCHEMA='$DB' AND CONSTRAINT_TYPE='UNIQUE'
  UNION ALL SELECT 'primary_key', COUNT(*) FROM information_schema.TABLE_CONSTRAINTS
    WHERE TABLE_SCHEMA='$DB' AND CONSTRAINT_TYPE='PRIMARY KEY'
  UNION ALL SELECT 'check_constraint', COUNT(*) FROM information_schema.TABLE_CONSTRAINTS
    WHERE TABLE_SCHEMA='$DB' AND CONSTRAINT_TYPE='CHECK'
  UNION ALL SELECT 'index', COUNT(DISTINCT TABLE_NAME, INDEX_NAME) FROM information_schema.STATISTICS
    WHERE TABLE_SCHEMA='$DB'
  UNION ALL SELECT 'column', COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA='$DB'
  UNION ALL SELECT 'partitioned_table', COUNT(DISTINCT TABLE_NAME) FROM information_schema.PARTITIONS
    WHERE TABLE_SCHEMA='$DB' AND PARTITION_NAME IS NOT NULL
  UNION ALL SELECT 'partition', COUNT(*) FROM information_schema.PARTITIONS
    WHERE TABLE_SCHEMA='$DB' AND PARTITION_NAME IS NOT NULL
  UNION ALL SELECT 'generated_column', COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA='$DB' AND EXTRA LIKE '%GENERATED%'
  UNION ALL SELECT 'invisible_column', COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA='$DB' AND EXTRA LIKE '%INVISIBLE%'
  UNION ALL SELECT 'invisible_index', COUNT(DISTINCT TABLE_NAME, INDEX_NAME) FROM information_schema.STATISTICS
    WHERE TABLE_SCHEMA='$DB' AND IS_VISIBLE='NO'
  UNION ALL SELECT 'functional_index_part', COUNT(*) FROM information_schema.STATISTICS
    WHERE TABLE_SCHEMA='$DB' AND EXPRESSION IS NOT NULL
  UNION ALL SELECT 'non_innodb_table', COUNT(*) FROM information_schema.TABLES
    WHERE TABLE_SCHEMA='$DB' AND TABLE_TYPE='BASE TABLE' AND ENGINE<>'InnoDB'
) x ORDER BY k;

SELECT 'TABLE', TABLE_NAME, ENGINE, IFNULL(TABLE_COLLATION,'-'), IFNULL(TABLE_COMMENT,'')
  FROM information_schema.TABLES
  WHERE TABLE_SCHEMA='$DB' AND TABLE_TYPE='BASE TABLE' ORDER BY BINARY TABLE_NAME;

SELECT 'VIEW', TABLE_NAME, IFNULL(CHECK_OPTION,'-'), IFNULL(IS_UPDATABLE,'-'), IFNULL(SECURITY_TYPE,'-')
  FROM information_schema.VIEWS WHERE TABLE_SCHEMA='$DB' ORDER BY BINARY TABLE_NAME;

SELECT 'ROUTINE', ROUTINE_TYPE, ROUTINE_NAME, IFNULL(SECURITY_TYPE,'-'), IFNULL(IS_DETERMINISTIC,'-')
  FROM information_schema.ROUTINES WHERE ROUTINE_SCHEMA='$DB'
  ORDER BY ROUTINE_TYPE, BINARY ROUTINE_NAME;

SELECT 'TRIGGER', TRIGGER_NAME, EVENT_MANIPULATION, ACTION_TIMING, EVENT_OBJECT_TABLE, ACTION_ORDER
  FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA='$DB'
  ORDER BY BINARY EVENT_OBJECT_TABLE, ACTION_TIMING, EVENT_MANIPULATION, ACTION_ORDER;

SELECT 'EVENT', EVENT_NAME, STATUS, IFNULL(INTERVAL_VALUE,'-'), IFNULL(INTERVAL_FIELD,'-'), IFNULL(ON_COMPLETION,'-')
  FROM information_schema.EVENTS WHERE EVENT_SCHEMA='$DB' ORDER BY BINARY EVENT_NAME;

SELECT 'COLUMN', CONCAT(TABLE_NAME,'.',COLUMN_NAME), COLUMN_TYPE, IS_NULLABLE,
       IFNULL(COLLATION_NAME,'-'), IFNULL(COLUMN_DEFAULT,'<null>'), IFNULL(EXTRA,'-'),
       IFNULL(GENERATION_EXPRESSION,'-')
  FROM information_schema.COLUMNS WHERE TABLE_SCHEMA='$DB'
  ORDER BY BINARY TABLE_NAME, ORDINAL_POSITION;

SELECT 'INDEX', TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX, IFNULL(COLUMN_NAME,'<expr>'),
       IF(NON_UNIQUE=0,'UNIQUE','-'), IFNULL(SUB_PART,'-'), IFNULL(COLLATION,'-'),
       INDEX_TYPE, IS_VISIBLE, IFNULL(EXPRESSION,'-')
  FROM information_schema.STATISTICS WHERE TABLE_SCHEMA='$DB'
  ORDER BY BINARY TABLE_NAME, BINARY INDEX_NAME, SEQ_IN_INDEX;

SELECT 'FK', k.CONSTRAINT_NAME, CONCAT(k.TABLE_NAME,'.',k.COLUMN_NAME),
       CONCAT(k.REFERENCED_TABLE_NAME,'.',k.REFERENCED_COLUMN_NAME),
       r.UPDATE_RULE, r.DELETE_RULE, k.ORDINAL_POSITION
  FROM information_schema.KEY_COLUMN_USAGE k
  JOIN information_schema.REFERENTIAL_CONSTRAINTS r
    ON r.CONSTRAINT_SCHEMA=k.CONSTRAINT_SCHEMA AND r.CONSTRAINT_NAME=k.CONSTRAINT_NAME
  WHERE k.TABLE_SCHEMA='$DB' AND k.REFERENCED_TABLE_NAME IS NOT NULL
  ORDER BY BINARY k.CONSTRAINT_NAME, k.ORDINAL_POSITION;

SELECT 'CHECK', CONSTRAINT_NAME, CHECK_CLAUSE FROM information_schema.CHECK_CONSTRAINTS
  WHERE CONSTRAINT_SCHEMA='$DB' ORDER BY BINARY CONSTRAINT_NAME;

SELECT 'PARTITION', TABLE_NAME, PARTITION_NAME, IFNULL(PARTITION_METHOD,'-'),
       IFNULL(PARTITION_EXPRESSION,'-'), IFNULL(PARTITION_DESCRIPTION,'-')
  FROM information_schema.PARTITIONS
  WHERE TABLE_SCHEMA='$DB' AND PARTITION_NAME IS NOT NULL
  ORDER BY BINARY TABLE_NAME, PARTITION_ORDINAL_POSITION;

SELECT 'DEFINER','routine', ROUTINE_NAME, DEFINER FROM information_schema.ROUTINES WHERE ROUTINE_SCHEMA='$DB'
UNION ALL SELECT 'DEFINER','view', TABLE_NAME, DEFINER FROM information_schema.VIEWS WHERE TABLE_SCHEMA='$DB'
UNION ALL SELECT 'DEFINER','trigger', TRIGGER_NAME, DEFINER FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA='$DB'
UNION ALL SELECT 'DEFINER','event', EVENT_NAME, DEFINER FROM information_schema.EVENTS WHERE EVENT_SCHEMA='$DB'
ORDER BY 2, 3;   -- ⚠️ UNION 은 정렬을 보장하지 않는다. 빠뜨리면 내용이 같은데 diff 가 어긋난다 (실제로 겪음)
"
